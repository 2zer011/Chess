const G = {};
for (const [k, v] of Object.entries(RAW)) G[k] = v.split('/');

const glyph = ch => G[ch] || G['?'];
export const FONT_GLYPHS = G;

export function textW(s, scale = 1) {
  let w = 0;
  for (const ch of String(s).toUpperCase()) w += (glyph(ch)[0].length + 1) * scale;
  return Math.max(0, w - scale);
}

// o: { scale, shadow (palette key), align: 'l' | 'c' | 'r' }
export function text(c, s, x, y, col = '5', o = {}) {
  const sc = o.scale || 1;
  s = String(s).toUpperCase();
  if (o.align === 'c') x -= textW(s, sc) >> 1;
  if (o.align === 'r') x -= textW(s, sc);
  x = Math.round(x); y = Math.round(y);
  const pass = (col2, dx, dy) => {
    c.fillStyle = C[col2] || col2;
    let cx = x + dx;
    for (const ch of s) {
      const g = glyph(ch);
      for (let r = 0; r < 5; r++) for (let q = 0; q < g[r].length; q++) {
        if (g[r][q] === '1') c.fillRect(cx + q * sc, y + dy + r * sc, sc, sc);
      }
      cx += (g[0].length + 1) * sc;
    }
  };
  if (o.shadow) pass(o.shadow, sc, sc);
  pass(col, 0, 0);
}

// Greedy word wrap to a pixel width.
export function wrap(s, maxW) {
  const lines = []; let cur = '';
  for (const w of String(s).toUpperCase().split(' ')) {
    const next = cur ? cur + ' ' + w : w;
    if (textW(next) > maxW && cur) { lines.push(cur); cur = w; } else cur = next;
  }
  if (cur) lines.push(cur);
  return lines;
}
